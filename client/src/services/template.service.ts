export const templateService = {
  async getTemplates(category?: string): Promise<Template[]> {
    const apiBase = import.meta.env.VITE_API_URL || '/api'
    const query = category && category !== 'all' && category !== 'Barchasi'
      ? `?category=${encodeURIComponent(category)}`
      : ''
    
    try {
      const res = await fetch(`${apiBase}/templates${query}`)
      if (res.ok) {
        const data = await res.json()
        if (Array.isArray(data) && data.length > 0) {
          // Sort: Palace Romance, Royal Gold, Uzbek Heritage on top
          return data.sort((a, b) => {
            if (a.id === 'palace-romance') return -1
            if (b.id === 'palace-romance') return 1
            if (a.priceTier === 'PREMIUM' && b.priceTier !== 'PREMIUM') return -1
            if (b.priceTier === 'PREMIUM' && a.priceTier !== 'PREMIUM') return 1
            return 0
          })
        }
      }
    } catch {
      // Fallback to local data
    }

    // Filter fallback
    if (category && category !== 'all' && category !== 'Barchasi') {
      return FALLBACK_TEMPLATES.filter((t) => t.category === category)
    }
    return FALLBACK_TEMPLATES
  },

  async getTemplateById(id: string): Promise<Template> {
    const apiBase = import.meta.env.VITE_API_URL || '/api'
    try {
      const res = await fetch(`${apiBase}/templates/${id}`)
      if (res.ok) return res.json()
    } catch {
      // Fallback
    }

    const found = FALLBACK_TEMPLATES.find((t) => t.id === id)
    if (found) return found
    throw new Error('Shablon topilmadi')
  },
}
